"""
Metode Heun (Modified Euler / Runge-Kutta Orde 2)
"""


def f(x, y):
  return (4 * x**3 - 2 * x + 1) / (2 + y)


def metode_heun(f, x_awal, y_awal, x_target, N):
  h = (x_target - x_awal) / N
  x, y = x_awal, y_awal
  tabel = []

  for i in range(N):
    k1 = f(x, y)
    y_predict = y + h * k1
    k2 = f(x + h, y_predict)
    y_next = y + (h / 2) * (k1 + k2)
    tabel.append((i, x, y, k1, k2, y_next))
    x = x + h
    y = y_next

  return tabel, y


def cetak_tabel(tabel):
  print(f"{'i':3}{'xi':10}{'yi':12}{'k1':12}{'k2':12}{'yi+1':12}")
  print("-" * 61)
  for i, xi, yi, k1, k2, y_next in tabel:
    print(
        f"{i:<3}{xi:<10.4f}{yi:<12.4f}{k1:<12.4f}{k2:<12.4f}{y_next:<12.4f}"
    )


if __name__ == "__main__":
  x_awal, y_awal = 0.0, 1.0
  x_target = 2.0
  N = 15

  tabel, y_heun = metode_heun(f, x_awal, y_awal, x_target, N)

  print("     Tabel Iterasi Metode Heun  \n")
  cetak_tabel(tabel)
  print(f"\nHasil akhir Metode Heun y({x_target}) = {y_heun:.6f}")