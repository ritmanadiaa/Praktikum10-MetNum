import math

"""
Perhitungan Galat Absolut dan Relatif (Standalone/Jupyter Notebook)
Soal: dy/dx = (4*x^3 - 2*x + 1) / (2 + y)
Kondisi Awal: y(0) = 1, Target: y(2), N = 15
"""


# 1. Solusi Analitik (Eksak)
def solusi_eksak(x):
  return -2 + math.sqrt(2 * x**4 - 2 * x**2 + 2 * x + 9)


# 2. Fungsi PDB dy/dx = f(x, y)
def f(x, y):
  return (4 * x**3 - 2 * x + 1) / (2 + y)


# 3. Metode Euler
def metode_euler(f, x_awal, y_awal, x_target, N):
  h = (x_target - x_awal) / N
  x, y = x_awal, y_awal
  for _ in range(N):
    fi = f(x, y)
    y = y + h * fi
    x = x + h
  return y


# 4. Metode Heun
def metode_heun(f, x_awal, y_awal, x_target, N):
  h = (x_target - x_awal) / N
  x, y = x_awal, y_awal
  for _ in range(N):
    k1 = f(x, y)
    y_predict = y + h * k1
    k2 = f(x + h, y_predict)
    y = y + (h / 2) * (k1 + k2)
    x = x + h
  return y


# 5. Metode Runge-Kutta Orde 4 (RK4)
def metode_rk4(f, x_awal, y_awal, x_target, N):
  h = (x_target - x_awal) / N
  x, y = x_awal, y_awal
  for _ in range(N):
    k1 = f(x, y)
    k2 = f(x + h / 2, y + k1 * h / 2)
    k3 = f(x + h / 2, y + k2 * h / 2)
    k4 = f(x + h, y + k3 * h)
    y = y + (h / 6) * (k1 + 2 * k2 + 2 * k3 + k4)
    x = x + h
  return y


# Main Program
if __name__ == "__main__":
  x_awal, y_awal = 0.0, 1.0
  x_target = 2.0
  N = 15

  # Hitung Nilai Pendekatan dan Eksak
  y_eksak = solusi_eksak(x_target)
  y_euler = metode_euler(f, x_awal, y_awal, x_target, N)
  y_heun = metode_heun(f, x_awal, y_awal, x_target, N)
  y_rk4 = metode_rk4(f, x_awal, y_awal, x_target, N)

  metodes = [
      ("Euler", y_euler),
      ("Heun", y_heun),
      ("Runge-Kutta Orde 4", y_rk4),
  ]

  print("=" * 75)
  print(f"PERBANDINGAN GALAT PADA x = {x_target} (N = {N})")
  print(f"Solusi Eksak (Analitik): {y_eksak:.6f}")
  print("=" * 75)
  print(
      f"{'Metode':<20} | {'Hasil (y)':<12} | {'Galat Absolut':<15} |"
      f" {'Galat Relatif (%)':<15}"
  )
  print("-" * 75)

  for nama, y_val in metodes:
    galat_abs = abs(y_eksak - y_val)
    galat_rel = (galat_abs / abs(y_eksak)) * 100
    print(
        f"{nama:<20} | {y_val:<12.6f} | {galat_abs:<15.6f} |"
        f" {galat_rel:<15.4f}%"
    )

  print("=" * 75)