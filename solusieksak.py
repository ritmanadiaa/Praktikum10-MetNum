import math

# Soal: dy/dx = (4*x^3 - 2*x + 1) / (2 + y)
# Kondisi Awal: y(0) = 1
# Mencari solusi eksak di x = 2

def solusi_eksak(x):
  # y(x) = -2 + sqrt(2*x^4 - 2*x^2 + 2*x + 9)
  return -2 + math.sqrt(2 * x**4 - 2 * x**2 + 2 * x + 9)


if __name__ == "__main__":
  x_target = 2.0
  y_eksak = solusi_eksak(x_target)

  print("=" * 40)
  print("SOLUSI ANALITIK (EKSAK)")
  print("=" * 40)
  print(f"Nilai y({x_target}) = {y_eksak:.6f}")